// Bundles self-hosted vendor code and Rifat's Cloudflare Pages Function:
//   src/smooth.js   -> assets/vendor/smooth.js   (Lenis, MIT)
//   src/rifat-fn.js -> functions/api/rifat.js    (Anthropic TypeScript SDK, MIT; bundled so the Pages deploy needs no npm install)
import { build } from 'esbuild';
import fs from 'node:fs';
const common = { bundle: true, format: 'esm', minify: true, legalComments: 'none', target: 'es2022' };
await build({ ...common, entryPoints: ['src/smooth.js'], outfile: 'assets/vendor/smooth.js', banner: { js: '/* Lenis (MIT, (c) darkroom.engineering) */' } });
await build({
  ...common, entryPoints: ['src/rifat-fn.js'], outfile: 'functions/api/rifat.js', platform: 'browser', conditions: ['worker', 'workerd'],
  banner: { js: '/* Rifat Pages Function. Generated by build.mjs from src/rifat-fn.js; edit the source, not this file. Includes the Anthropic TypeScript SDK (MIT). */' },
});
for (const f of ['assets/vendor/smooth.js', 'functions/api/rifat.js']) fs.writeFileSync(f, fs.readFileSync(f, 'utf8').replace(/[ \t]+$/gm, ''));
